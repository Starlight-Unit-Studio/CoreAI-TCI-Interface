#!/usr/bin/env python3
"""Offline regression: recover real output bytes, reject symlinks and scripts."""
from __future__ import annotations

import hashlib
import os
from pathlib import Path
import sys
import tempfile

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from ember_artifacts import (  # noqa: E402
    recover_workspace_outputs, recover_stdout_html, collect_outputs,
)

with tempfile.TemporaryDirectory(prefix="coreui-artifact-regression-") as root:
    base = Path(root)
    work = base / "work"
    output = base / "output"
    work.mkdir()
    output.mkdir()
    (work / "main.py").write_text("print('secret source')\n", encoding="utf-8")
    (work / "mini_game.html").write_text(
        "<!doctype html><html><body>Mini Game</body></html>", encoding="utf-8"
    )
    sub = work / "game"
    sub.mkdir()
    (sub / "style.css").write_text("body{margin:0}", encoding="utf-8")
    (sub / "game.js").write_text("console.log('ready')", encoding="utf-8")
    (work / "link.html").symlink_to(work / "mini_game.html")
    (work / ".hidden.html").write_text("hidden", encoding="utf-8")
    found = recover_workspace_outputs(work, output)
    assert found == 3, f"unexpected workspace recovery: {found}"
    assert sorted(p.name for p in output.iterdir()) == [
        "game.js", "mini_game.html", "style.css"
    ]
    assert b"Mini Game" in (output / "mini_game.html").read_bytes()
    assert not (output / "main.py").exists()
    assert not (output / "link.html").exists()
    assert recover_workspace_outputs(work, output) == 0, "no duplicate files"

    manifest = collect_outputs(output, base, 123)
    files = manifest["files"]
    assert len(files) == 3 and manifest["version"] == 1
    for item in files:
        real = base / "artifacts" / item["storage_key"]
        assert hashlib.sha256(real.read_bytes()).hexdigest() == item["sha256"]

with tempfile.TemporaryDirectory(prefix="coreui-html-regression-") as root:
    output = Path(root)
    html = "<!doctype html><html><body>Generated by print() test</body></html>"
    assert recover_stdout_html(html, output)
    assert (output / "generated.html").read_text(encoding="utf-8") == html
    assert not recover_stdout_html(html, output)
    assert not recover_stdout_html("Done! file:///tmp/fake.html", output)

print("P06 Python workspace output recovery selftest: OK")
